/** Σταθερό αναγνωριστικό για τα τμήματα και τη χωριστή 24ωρη υπηρεσία. */
export type UnitId = string;
/** Το backend ορίζει τον ρόλο· ο browser τον χρησιμοποιεί μόνο για την εμφάνιση. */
export type Role = 'admin' | 'user';

/** Ταυτότητα και δικαιώματα επεξεργασίας από το login και το /auth/me. */
export interface User {
  /** Αναγνωριστικό χρήστη από το backend· το εμφανιζόμενο όνομα δεν είναι ID. */
  id: string;
  /** Όνομα σύνδεσης που στέλνεται στο endpoint πιστοποίησης. */
  username: string;
  /** Σύντομη ετικέτα που εμφανίζεται στην κεφαλίδα της εφαρμογής. */
  displayName: string;
  /** Οι διαχειριστές εργάζονται σε πολλά τμήματα· οι απλοί χρήστες σε ένα. */
  role: Role;
  /** Τμήμα του απλού χρήστη· null για τους διαχειριστές ΑΚΠ/ΑΥΜ. */
  departmentId: UnitId | null;
  /** Δικαιώματα επεξεργασίας από τον server, που ελέγχονται ξανά πριν την αποθήκευση. */
  editableUnitIds: UnitId[];
}

/** Εγγραφή καταλόγου τμημάτων· το backend ορίζει τη σύνθεση και τις βάρδιες. */
export interface Department {
  /** Σταθερό ID που χρησιμοποιείται στα API paths προσωπικού και προγράμματος. */
  id: UnitId;
  /** Ελληνική ονομασία που εμφανίζεται σε πίνακες και λίστες επιλογής. */
  name: string;
  /** Ξεχωρίζει τα Δ4/Δ5/ΕΜΚ από τη χωριστή 24ωρη υπηρεσία. */
  kind: 'department' | 'service';
  /** Ρυθμισμένες βάρδιες του τμήματος· ο αριθμός τους δεν είναι πάντα τρεις. */
  shiftTypes: ShiftType[];
}

/** Εγγραφή καταλόγου μόνο για ανάγνωση· οι βάρδιες δεν αλλάζουν τη σύνθεση προσωπικού. */
export interface StaffMember {
  /** Σταθερό ID προσωπικού που χρησιμοποιούν οι αναθέσεις. */
  id: string;
  /** Όνομα που χρησιμοποιείται μόνο για εμφάνιση και εξαγωγή Excel. */
  fullName: string;
  /** Σταθερό οργανικό τμήμα που έχει ορίσει το backend. */
  departmentId: UnitId;
  /** Τμήματα στα οποία το άτομο μπορεί να επιλεγεί για βάρδια. */
  availableForUnitIds: UnitId[];
}

/** Μία διαθέσιμη βάρδια που έχει ρυθμιστεί για συγκεκριμένο τμήμα. */
export interface ShiftType {
  /** ID που συνδέει την ανάθεση του προγράμματος με αυτή τη βάρδια. */
  id: string;
  /** Αναγνώσιμη ονομασία βάρδιας· το frontend δεν επινοεί ωράρια. */
  label: string;
}

/** Αποθηκευμένη ανάθεση μηδέν ή περισσότερων ατόμων σε βάρδια μίας ημέρας. */
export interface ShiftAssignment {
  /** Σταθερό ID ανάθεσης από το backend (προβλέψιμο στο mock mode). */
  id: string;
  /** Ημερολογιακή ημέρα Αθήνας σε μορφή YYYY-MM-DD, χωρίς μετατροπή σε UTC. */
  date: string;
  /** Τμήμα ή 24ωρη υπηρεσία στην οποία ανήκει η ανάθεση. */
  unitId: UnitId;
  /** Πρέπει να ταιριάζει με ID βάρδιας που έχει ρυθμιστεί για το τμήμα. */
  shiftTypeId: string;
  /** Επιτρέπονται πολλά ID προσωπικού· κενός πίνακας σημαίνει χωρίς ανάθεση. */
  staffIds: string[];
  /** Ώρα τελευταίας ενημέρωσης, εφόσον παρέχεται από το API. */
  updatedAt?: string;
}

/** Πλήρες πρόγραμμα που επιστρέφεται για μία επιλεγμένη ημέρα. */
export interface DailyRoster {
  /** Ίδια ημερομηνία με αυτή που ζήτησε ο πίνακας ή η φόρμα. */
  date: string;
  /** Περιλαμβάνει όλα τα τμήματα· βάρδιες που λείπουν εμφανίζονται κενές. */
  assignments: ShiftAssignment[];
}

/** Αντικαθιστά τις αναθέσεις ενός τμήματος για μία ημέρα, χωρίς αλλαγή των άλλων. */
export interface SaveUnitAssignmentsRequest {
  /** Επιλεγμένη ημερολογιακή ημέρα. */
  date: string;
  /** Τμήμα που αλλάζει· το δικαίωμα ελέγχεται για αυτό το ID. */
  unitId: UnitId;
  /** Μία εγγραφή για κάθε ρυθμισμένη βάρδια του τμήματος. */
  assignments: { shiftTypeId: string; staffIds: string[] }[];
}

/** Δημόσιο αίτημα εγγραφής· η επιλογή τμήματος δεν δίνει δικαιώματα. */
export interface RegisterRequest {
  /** Όνομα αιτούντος· δεν αλλάζει τον κατάλογο προσωπικού. */
  fullName: string;
  /** Επιθυμητό όνομα σύνδεσης. */
  username: string;
  /** Στέλνεται μόνο στο endpoint πιστοποίησης· το frontend δεν το αποθηκεύει. */
  password: string;
  /** Τμήμα που δηλώνεται στο αίτημα για έλεγχο από το backend. */
  departmentId: UnitId;
}
